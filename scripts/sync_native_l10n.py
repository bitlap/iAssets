#!/usr/bin/env python3
"""Export iOS permission strings and widget text from the Dart catalogs.

Run after changing strings_*.dart. No network or translation service is used.
"""
import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STRING = r'''(?:'(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*")'''


def catalog(path):
    return {
        ast.literal_eval(key): ast.literal_eval(value.replace('\\$', '$'))
        for key, value in re.findall(
            '(' + STRING + r')\s*:\s*(' + STRING + ')', path.read_text()
        )
    }


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def main():
    catalogs = {}
    for path in sorted((ROOT / 'lib/l10n').glob('strings_*.dart')):
        code = path.stem.removeprefix('strings_')
        code = {'zh_hant': 'zh_Hant', 'pt_br': 'pt_BR', 'pt_pt': 'pt_PT'}.get(code, code)
        catalogs[code] = catalog(path)
    assert len(catalogs) == 33, 'Expected all 33 language catalogs'
    english = catalogs['en']
    widget_keys = [key for key in english if key.startswith('widget')]
    for code, table in catalogs.items():
        for key in widget_keys + ['iosPhotoLibraryUsage', 'iosFaceIDUsage']:
            assert key in table and table[key], (code, key)
        region = {'zh': 'zh-Hans', 'zh_Hant': 'zh-Hant'}.get(code, code.replace('_', '-'))
        folder = ROOT / 'ios/Runner' / f'{region}.lproj'
        folder.mkdir(exist_ok=True)
        (folder / 'InfoPlist.strings').write_text(
            '// Generated by scripts/sync_native_l10n.py.\n'
            '"CFBundleDisplayName" = "iAssets";\n'
            f'"NSPhotoLibraryUsageDescription" = {quoted(table["iosPhotoLibraryUsage"])};\n'
            f'"NSFaceIDUsageDescription" = {quoted(table["iosFaceIDUsage"])};\n'
        )

    words = []
    for key in widget_keys:
        native_key = key.removeprefix('widget')
        native_key = native_key[0].lower() + native_key[1:]
        values = ', '.join(f'{quoted(code)}: {quoted(table[key])}' for code, table in catalogs.items())
        words.append(f'    {quoted(native_key)}: [{values}],')
    generated = '''private enum WidgetWords {
  // Generated by scripts/sync_native_l10n.py from the app catalogs.
  static let words: [String: [String: String]] = [
''' + '\n'.join(words) + '''
  ]

  static func language(_ snapshot: AssetWidgetSnapshot?, locale: Locale = .current) -> String {
    if let language = snapshot?.language, words["total"]?[language] != nil { return language }
    var code = locale.language.languageCode?.identifier ?? "en"
    code = ["tl": "fil", "no": "nb", "iw": "he", "in": "id"][code] ?? code
    if code == "zh" {
      if locale.language.script?.identifier == "Hant" { return "zh_Hant" }
      if locale.language.script?.identifier == "Hans" { return "zh" }
      return ["TW", "HK", "MO"].contains(locale.region?.identifier ?? "") ? "zh_Hant" : "zh"
    }
    if code == "pt" { return locale.region?.identifier == "PT" ? "pt_PT" : "pt_BR" }
    return words["total"]?[code] != nil ? code : "en"
  }

  static func text(_ key: String, _ language: String) -> String {
    words[key]?[language] ?? words[key]?["en"] ?? key
  }
}

'''
    widget = ROOT / 'ios/AssetsWidget/AssetsWidget.swift'
    source = widget.read_text()
    start = source.index('private enum WidgetWords {')
    end = source.index('private struct AssetWidgetView:', start)
    source = source[:start] + generated + source[end:]
    widget.write_text(source)

    # The extension has no .lproj resources: declare the languages supplied by
    # WidgetWords so iOS also recognizes them when presenting the widget gallery.
    widget_plist = ROOT / 'ios/AssetsWidget/Info.plist'
    source = widget_plist.read_text()
    source = re.sub(r'  <key>CFBundleLocalizations</key>\n  <array>.*?</array>\n', '', source, flags=re.S)
    regions = [
        {'zh': 'zh-Hans', 'zh_Hant': 'zh-Hant'}.get(code, code.replace('_', '-'))
        for code in catalogs
    ]
    localized = '  <key>CFBundleLocalizations</key>\n  <array>\n'
    localized += ''.join(f'    <string>{region}</string>\n' for region in regions)
    localized += '  </array>\n'
    source = source.replace('  <key>NSExtension</key>', localized + '  <key>NSExtension</key>')
    widget_plist.write_text(source)

    project = ROOT / 'ios/Runner.xcodeproj/project.pbxproj'
    source = project.read_text()
    # Stable generated references. Re-running is idempotent.
    source = re.sub(r'^.*B10CA1[0-9A-F]{18}.*\n', '', source, flags=re.M)
    refs, children, regions = [], [], []
    for index, code in enumerate(sorted(set(catalogs) - {'en', 'zh', 'zh_Hant'})):
        region = code.replace('_', '-')
        identifier = f'B10CA1{index:018X}'
        refs.append(f'\t\t{identifier} /* {region} */ = {{isa = PBXFileReference; lastKnownFileType = text.plist.strings; name = "{region}"; path = "{region}.lproj/InfoPlist.strings"; sourceTree = "<group>"; }};\n')
        children.append(f'\t\t\t\t{identifier} /* {region} */,\n')
        regions.append(f'\t\t\t\t"{region}",\n')
    source = source.replace('/* End PBXFileReference section */', ''.join(refs) + '/* End PBXFileReference section */')
    group_start = source.index('A12345678900000000000005 /* InfoPlist.strings */ = {')
    insert = source.index('\n\t\t\t);', group_start)
    source = source[:insert] + '\n' + ''.join(children).rstrip('\n') + source[insert:]
    start = source.index('\t\t\tknownRegions = (')
    end = source.index('\n\t\t\t);', start)
    source = source[:start] + '\t\t\tknownRegions = (\n\t\t\t\ten,\n\t\t\t\tBase,\n\t\t\t\t"zh-Hans",\n\t\t\t\t"zh-Hant",\n' + ''.join(regions).rstrip('\n') + source[end:]
    project.write_text(source)
    print(f'Exported {len(catalogs)} languages to iOS permissions and widgets.')


if __name__ == '__main__':
    main()
